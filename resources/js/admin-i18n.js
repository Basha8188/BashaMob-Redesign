const originalText = new WeakMap();
const originalAttributes = new WeakMap();
let activeLocale = document.documentElement.dataset.locale || 'ar';
let applyingTranslation = false;

const replaceKeepingSpace = (raw, translated) => {
    const start = raw.match(/^\s*/)?.[0] || '';
    const end = raw.match(/\s*$/)?.[0] || '';
    return `${start}${translated}${end}`;
};

const translateTextNode = node => {
    const raw = node.nodeValue || '';
    const value = raw.trim();
    if (!value) return;
    if (!originalText.has(node) || adminTranslations[value]) originalText.set(node, raw);
    const arabicRaw = originalText.get(node);
    const arabicValue = arabicRaw.trim();
    const nextValue = activeLocale === 'en' && adminTranslations[arabicValue]
        ? replaceKeepingSpace(arabicRaw, adminTranslations[arabicValue])
        : arabicRaw;
    if (node.nodeValue !== nextValue) node.nodeValue = nextValue;
};

const translateAttributes = element => {
    const names = ['placeholder', 'title', 'aria-label'];
    if (!originalAttributes.has(element)) originalAttributes.set(element, {});
    const originals = originalAttributes.get(element);
    names.forEach(name => {
        const current = element.getAttribute?.(name);
        if (!current) return;
        if (!originals[name] || adminTranslations[current]) originals[name] = current;
        element.setAttribute(name, activeLocale === 'en' && adminTranslations[originals[name]] ? adminTranslations[originals[name]] : originals[name]);
    });
};

const translateTree = root => {
    if (!root) return;
    applyingTranslation = true;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode: node => ['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    while (walker.nextNode()) translateTextNode(walker.currentNode);
    if (root.matches?.('[placeholder],[title],[aria-label]')) translateAttributes(root);
    root.querySelectorAll?.('[placeholder],[title],[aria-label]').forEach(translateAttributes);
    applyingTranslation = false;
};

const applyAdminLocale = locale => {
    activeLocale = locale;
    const html = document.documentElement;
    html.lang = locale;
    html.dir = locale === 'ar' ? 'rtl' : 'ltr';
    html.dataset.locale = locale;
    localStorage.setItem('basha-admin-language', locale);
    translateTree(document.body);
    const label = document.querySelector('.language-label');
    if (label) label.textContent = locale === 'ar' ? 'EN' : 'عربي';
};

document.addEventListener('DOMContentLoaded', () => {
    if (!document.body.classList.contains('admin-body')) return;
    applyAdminLocale(activeLocale);
    document.getElementById('admin-language-toggle')?.addEventListener('click', () => applyAdminLocale(activeLocale === 'ar' ? 'en' : 'ar'));
    new MutationObserver(mutations => {
        if (applyingTranslation || activeLocale !== 'en') return;
        mutations.forEach(mutation => {
            if (mutation.type === 'characterData') translateTextNode(mutation.target);
            mutation.addedNodes.forEach(node => node.nodeType === Node.ELEMENT_NODE ? translateTree(node) : node.nodeType === Node.TEXT_NODE && translateTextNode(node));
        });
    }).observe(document.body, { subtree: true, childList: true, characterData: true });
});
